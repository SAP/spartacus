import {
  noop,
  Rule,
  SchematicContext,
  SchematicsException,
  Tree,
} from '@angular-devkit/schematics';
import {
  isSsrUsed,
  prependNgAllowedHostsToServeSsr,
} from '../../../../shared/utils/package-utils';

/**
 * Ensures every `serve:ssr*` script in `package.json` sets the `NG_ALLOWED_HOSTS`
 * environment variable.
 *
 * Angular 22's SSR engine rejects any request whose hostname is not in the
 * `NG_ALLOWED_HOSTS` allowlist. The `serve:ssr:<app>` script generated by
 * Angular's SSR schematic does not set it, so after the upgrade running
 * `serve:ssr` responds with HTTP 500. This migration back-fills the variable
 * for existing apps (idempotent - scripts that already set it are left as-is).
 */
function addNgAllowedHostsToServeSsr(): Rule {
  return (tree: Tree, context: SchematicContext) => {
    context.logger.info(
      '\n⌛️ Adding "NG_ALLOWED_HOSTS" to "serve:ssr" script(s) in package.json...'
    );

    const pkgPath = '/package.json';
    const pkg = tree.readJson(pkgPath) as {
      scripts?: Record<string, string>;
    } | null;

    if (pkg === null) {
      throw new SchematicsException('Could not find package.json');
    }

    const scripts = pkg.scripts ?? {};
    if (!prependNgAllowedHostsToServeSsr(scripts)) {
      context.logger.info(
        '  ↳ No "serve:ssr" script needs "NG_ALLOWED_HOSTS" - skipping'
      );
      return tree;
    }

    pkg.scripts = scripts;
    tree.overwrite(pkgPath, JSON.stringify(pkg, null, 2));
    context.logger.info(
      '✅ Added "NG_ALLOWED_HOSTS" to "serve:ssr" script(s) in package.json'
    );

    return tree;
  };
}

/**
 * Migration to set `NG_ALLOWED_HOSTS` on the `serve:ssr` script.
 *
 * This migration only runs for apps that use SSR (Server-Side Rendering).
 */
export function migrate(): Rule {
  return (tree: Tree, context: SchematicContext) => {
    if (!isSsrUsed(tree)) {
      context.logger.info(
        '\n  ↳ SSR is not configured - skipping NG_ALLOWED_HOSTS migration'
      );
      return noop();
    }

    return addNgAllowedHostsToServeSsr()(tree, context);
  };
}
